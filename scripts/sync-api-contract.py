#!/usr/bin/env python3
"""Generate or check TypeScript wire types against the pinned TTSForge API contract."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import tempfile
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "runtime/runtime-manifest.toml"
SCHEMA_PATH = ROOT / "api/ttsforge-v1.openapi.json"
GENERATED_PATH = ROOT / "src/lib/api/generated.ts"
CONTRACT_PATH = ROOT / "src/lib/api/contract.ts"
GENERATOR = "openapi-typescript@7.6.1"


def generate_types() -> bytes:
    with tempfile.TemporaryDirectory() as directory:
        output_path = Path(directory) / "generated.ts"
        subprocess.run(
            [
                "npx",
                "--yes",
                GENERATOR,
                str(SCHEMA_PATH),
                "-o",
                str(output_path),
            ],
            cwd=ROOT,
            check=True,
        )
        return output_path.read_bytes()



def generate_contract(api_version: int) -> bytes:
    content = (
        "// This file is generated by scripts/sync-api-contract.py.\n"
        "// Do not edit manually.\n"
        f"export const TTSFORGE_API_VERSION = {api_version} as const;\n"
    )
    return content.encode("utf-8")

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated types are stale")
    args = parser.parse_args()

    manifest = tomllib.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    schema_hash = hashlib.sha256(SCHEMA_PATH.read_bytes()).hexdigest()

    if manifest["schema"] != 2:
        raise SystemExit("Unsupported runtime manifest schema")
    if not re.fullmatch(r"\d+\.\d+\.\d+", manifest["ttsforge_version"]):
        raise SystemExit("Runtime TTSForge version must be an exact stable version")
    if str(manifest["api_version"]) != schema["info"]["version"]:
        raise SystemExit("Runtime API version does not match the vendored OpenAPI schema")
    if manifest["openapi_sha256"] != schema_hash:
        raise SystemExit("Vendored OpenAPI schema hash does not match runtime/runtime-manifest.toml")

    generated = generate_types()
    contract = generate_contract(manifest["api_version"])
    if args.check:
        if not GENERATED_PATH.is_file() or GENERATED_PATH.read_bytes() != generated:
            raise SystemExit("Generated API types are stale; run npm run contract:generate")
        if not CONTRACT_PATH.is_file() or CONTRACT_PATH.read_bytes() != contract:
            raise SystemExit("Generated API version is stale; run npm run contract:generate")
        print(
            f"Contract verified for TTSForge {manifest['ttsforge_version']} "
            f"API v{manifest['api_version']} ({schema_hash})"
        )
        return 0

    GENERATED_PATH.parent.mkdir(parents=True, exist_ok=True)
    GENERATED_PATH.write_bytes(generated)
    CONTRACT_PATH.write_bytes(contract)
    print(f"Generated API types for TTSForge {manifest['ttsforge_version']} API v{manifest['api_version']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
